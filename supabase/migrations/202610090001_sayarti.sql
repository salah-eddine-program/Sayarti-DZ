-- Fresh Supabase schema. This does not import any legacy database records.
begin;

create table public.app_users (
  id integer generated by default as identity primary key,
  auth_user_id uuid not null unique references auth.users(id) on delete cascade,
  open_id text not null unique,
  name text,
  email varchar(320),
  login_method text default 'email',
  role text not null default 'user' check (role in ('user', 'admin')),
  language text not null default 'ar' check (language in ('ar', 'fr', 'en')),
  theme text not null default 'light' check (theme in ('light', 'dark')),
  profile_link varchar(2048),
  plan text not null default 'free' check (plan in ('free', 'premium')),
  premium_expires_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  last_signed_in timestamptz not null default now()
);

create table public.vehicles (
  id integer generated by default as identity primary key,
  auth_user_id uuid not null references public.app_users(auth_user_id) on delete cascade,
  brand varchar(80) not null,
  model varchar(80) not null,
  year integer not null check (year between 1900 and 2200),
  fuel_type text not null check (fuel_type in ('diesel', 'petrol', 'lpg', 'electric')),
  mileage integer not null default 0 check (mileage between 0 and 10000000),
  plate_number varchar(32),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (id, auth_user_id)
);

create table public.maintenance (
  id integer generated by default as identity primary key,
  auth_user_id uuid not null references public.app_users(auth_user_id) on delete cascade,
  vehicle_id integer not null,
  title varchar(160) not null,
  service_date date not null,
  mileage integer not null check (mileage between 0 and 10000000),
  cost integer not null default 0 check (cost between 0 and 100000000),
  notes text,
  invoice_url varchar(2048),
  created_at timestamptz not null default now(),
  foreign key (vehicle_id, auth_user_id) references public.vehicles(id, auth_user_id) on delete cascade
);

create table public.expenses (
  id integer generated by default as identity primary key,
  auth_user_id uuid not null references public.app_users(auth_user_id) on delete cascade,
  vehicle_id integer not null,
  title varchar(160) not null,
  category text not null check (category in ('service', 'fuel', 'parts', 'other')),
  amount integer not null default 0 check (amount between 0 and 100000000),
  expense_date date not null,
  created_at timestamptz not null default now(),
  foreign key (vehicle_id, auth_user_id) references public.vehicles(id, auth_user_id) on delete cascade
);

create table public.fuel_logs (
  id integer generated by default as identity primary key,
  auth_user_id uuid not null references public.app_users(auth_user_id) on delete cascade,
  vehicle_id integer not null,
  amount integer not null default 0 check (amount between 0 and 100000000),
  liters integer not null default 0 check (liters between 0 and 10000),
  price_per_liter integer not null default 0 check (price_per_liter between 0 and 1000000),
  mileage integer not null check (mileage between 0 and 10000000),
  fuel_date date not null,
  created_at timestamptz not null default now(),
  foreign key (vehicle_id, auth_user_id) references public.vehicles(id, auth_user_id) on delete cascade
);

create table public.documents (
  id integer generated by default as identity primary key,
  auth_user_id uuid not null references public.app_users(auth_user_id) on delete cascade,
  vehicle_id integer not null,
  title varchar(160) not null,
  expires_on date,
  file_url varchar(2048),
  created_at timestamptz not null default now(),
  foreign key (vehicle_id, auth_user_id) references public.vehicles(id, auth_user_id) on delete cascade
);

create index vehicles_owner_updated_idx on public.vehicles(auth_user_id, updated_at desc);
create index maintenance_owner_date_idx on public.maintenance(auth_user_id, service_date desc);
create index expenses_owner_date_idx on public.expenses(auth_user_id, expense_date desc);
create index fuel_logs_owner_date_idx on public.fuel_logs(auth_user_id, fuel_date desc);
create index documents_owner_date_idx on public.documents(auth_user_id, expires_on desc);

create function public.set_updated_at() returns trigger
language plpgsql set search_path = '' as $$
begin
  new.updated_at := now();
  return new;
end;
$$;
create trigger app_users_updated_at before update on public.app_users
for each row execute function public.set_updated_at();
create trigger vehicles_updated_at before update on public.vehicles
for each row execute function public.set_updated_at();

alter table public.app_users enable row level security;
alter table public.vehicles enable row level security;
alter table public.maintenance enable row level security;
alter table public.expenses enable row level security;
alter table public.fuel_logs enable row level security;
alter table public.documents enable row level security;

revoke all on public.app_users, public.vehicles, public.maintenance, public.expenses, public.fuel_logs, public.documents from anon, authenticated;
grant usage on schema public to authenticated, service_role;
grant all on public.app_users, public.vehicles, public.maintenance, public.expenses, public.fuel_logs, public.documents to service_role;
grant usage, select on all sequences in schema public to service_role;
-- Only server-side verified auth can create profiles or alter privileged fields.
grant select on public.app_users to authenticated;
grant update (language, theme, profile_link) on public.app_users to authenticated;
create policy app_users_select_own on public.app_users for select to authenticated
using (auth_user_id = (select auth.uid()));
create policy app_users_update_own on public.app_users for update to authenticated
using (auth_user_id = (select auth.uid())) with check (auth_user_id = (select auth.uid()));

-- Writes intentionally go through validated tRPC procedures; RLS protects reads
-- even if the anonymous client talks to the PostgREST endpoint directly.
grant select on public.vehicles, public.maintenance, public.expenses, public.fuel_logs, public.documents to authenticated;
create policy vehicles_select_own on public.vehicles for select to authenticated
using (auth_user_id = (select auth.uid()));
create policy maintenance_select_own on public.maintenance for select to authenticated
using (auth_user_id = (select auth.uid()));
create policy expenses_select_own on public.expenses for select to authenticated
using (auth_user_id = (select auth.uid()));
create policy fuel_logs_select_own on public.fuel_logs for select to authenticated
using (auth_user_id = (select auth.uid()));
create policy documents_select_own on public.documents for select to authenticated
using (auth_user_id = (select auth.uid()));

commit;
